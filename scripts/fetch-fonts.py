"""Download Google Fonts (woff2, latin + cyrillic) into frontend/public/fonts and write fonts.css."""
import os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "frontend", "public", "fonts")
URL = "https://fonts.googleapis.com/css2?family=Rubik:wght@400;500;600;700;800;900&display=swap"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
KEEP = {"latin", "latin-ext"}

os.makedirs(OUT, exist_ok=True)


def get(url):
    last = None
    for _ in range(5):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=40).read()
        except Exception as e:  # flaky network: retry
            last = e
    raise last


css = get(URL).decode()
blocks = re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
out_css = []
for subset, block in blocks:
    if subset not in KEEP:
        continue
    fam = re.search(r"font-family: '([^']+)'", block).group(1)
    weight = re.search(r"font-weight: (\d+)", block).group(1)
    src = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
    # Variable fonts: every weight of a family/subset points at the same file.
    name = f"{fam.lower()}-{subset}.woff2"
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        data = get(src)
        with open(path, "wb") as f:
            f.write(data)
    out_css.append(f"/* {subset} */\n" + block.replace(src, f"/fonts/{name}"))

with open(os.path.join(ROOT, "frontend", "public", "css", "fonts.css"), "w", encoding="utf-8") as f:
    f.write("/* Self-hosted Google Fonts (generated by scripts/fetch-fonts.py) */\n" + "\n".join(out_css) + "\n")
print(len(out_css), "faces;", len(os.listdir(OUT)), "files")


